"""Metadata fallback via YouTube's oEmbed endpoint (no API key needed).

Used when yt-dlp can't fetch audio (fallback ladder step 3, architecture §7):
the track still gets a title/artist so the archive stays browsable. Embed
hosting never runs yt-dlp, so it also reads lengths here (``fetch_duration``)
and, for YouTube's auto-generated "art track" uploads, the artists credited
in the description (``fetch_watch_credits``), the same block yt-dlp reads.
"""

from __future__ import annotations

import json
import logging
import re

import httpx

from ..net import http_client

log = logging.getLogger(__name__)

OEMBED_URL = "https://www.youtube.com/oembed"
WATCH_URL = "https://www.youtube.com/watch"
# oEmbed has no length, so the watch page is read for one: the player
# response embedded in it carries "lengthSeconds", and the page's schema.org
# markup an ISO 8601 duration. A browser's User-Agent gets the regular page;
# the consent cookie skips the EU cookie wall that would stand in for it.
WATCH_HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
    ),
    "Accept-Language": "en-US,en;q=0.9",
    "Cookie": "CONSENT=YES+1; SOCS=CAI",
}
_LENGTH_SECONDS = re.compile(r'"lengthSeconds"\s*:\s*"(\d+)"')
_ISO_DURATION = re.compile(
    r'itemprop="duration"\s+content="PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?"'
)
# The player response embedded in the watch page carries the description as
# a JSON string. The first match is the video's own.
_SHORT_DESCRIPTION = re.compile(r'"shortDescription"\s*:\s*"((?:[^"\\]|\\.)*)"')
# How YouTube opens and closes the description of an auto-generated art
# track (an upload on a "<Artist> - Topic" or "Release - Topic" channel).
_ART_TRACK_START = "Provided to YouTube by"
_ART_TRACK_END = "Auto-generated by YouTube."


async def fetch_oembed(
    video_id: str, client: httpx.AsyncClient | None = None
) -> dict[str, str] | None:
    """Return {"title", "artist", "thumbnail"} or None if unresolvable.

    Pass the caller's ``client`` to reuse its connection pool: the cacher
    resolves a whole backfill this way, and a fresh TLS handshake per video
    was most of each lookup's time. Without one, a throwaway client is used."""
    watch_url = f"https://www.youtube.com/watch?v={video_id}"
    params = {"url": watch_url, "format": "json"}
    try:
        if client is None:
            async with http_client(timeout=15) as own:
                resp = await own.get(OEMBED_URL, params=params)
        else:
            resp = await client.get(OEMBED_URL, params=params)
        resp.raise_for_status()
        data = resp.json()
    except Exception:
        log.warning("oEmbed lookup failed for %s", video_id, exc_info=True)
        return None
    return {
        "title": data.get("title", ""),
        "artist": data.get("author_name", ""),
        "thumbnail": data.get("thumbnail_url", ""),
    }


def parse_watch_duration(html: str) -> float | None:
    """A video's length in seconds from its watch page, or None."""
    match = _LENGTH_SECONDS.search(html)
    if match and int(match.group(1)) > 0:
        return float(match.group(1))
    match = _ISO_DURATION.search(html)
    if match:
        h, m, s = (int(g or 0) for g in match.groups())
        seconds = h * 3600 + m * 60 + s
        if seconds > 0:
            return float(seconds)
    return None


def parse_watch_description(html: str) -> str | None:
    """The video's description from its watch page, or None."""
    match = _SHORT_DESCRIPTION.search(html)
    if not match:
        return None
    try:
        text = json.loads(f'"{match.group(1)}"')
    except ValueError:
        return None
    return text if isinstance(text, str) else None


def parse_art_track_artists(description: str | None) -> str | None:
    """The artists credited in an auto-generated art track's description,
    joined with ", ", or None when it isn't one.

    YouTube writes these descriptions to one pattern::

        Provided to YouTube by <label>

        <Title> · <Artist> · <Artist 2>

        <Album>
        ...
        Auto-generated by YouTube.

    which is where yt-dlp's music credits come from too. Anything that
    doesn't open and close the way YouTube's do is somebody's own text and
    is left alone: a wrong artist is worse than none, which Fix artists
    lists for a person to fill in."""
    text = (description or "").strip()
    if not (text.startswith(_ART_TRACK_START) and text.endswith(_ART_TRACK_END)):
        return None
    paragraphs = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    if len(paragraphs) < 3:
        return None
    parts = [p.strip() for p in paragraphs[1].split("\u00b7")]
    artists = [p for p in parts[1:] if p]
    if len(parts) < 2 or not parts[0] or not artists:
        return None
    return ", ".join(artists)


async def fetch_watch_page(
    video_id: str, client: httpx.AsyncClient | None = None
) -> str | None:
    """A video's watch page as text, or None if YouTube didn't serve it."""
    params = {"v": video_id}
    try:
        if client is None:
            async with http_client(timeout=15) as own:
                resp = await own.get(WATCH_URL, params=params, headers=WATCH_HEADERS)
        else:
            resp = await client.get(WATCH_URL, params=params, headers=WATCH_HEADERS)
        resp.raise_for_status()
    except Exception:
        log.warning("watch page lookup failed for %s", video_id, exc_info=True)
        return None
    return resp.text


async def fetch_duration(
    video_id: str, client: httpx.AsyncClient | None = None
) -> float | None:
    """A video's length in seconds from YouTube, or None if it can't be read."""
    html = await fetch_watch_page(video_id, client)
    if html is None:
        return None
    seconds = parse_watch_duration(html)
    if seconds is None:
        log.info("no length on the watch page for %s", video_id)
    return seconds


async def fetch_watch_credits(
    video_id: str, client: httpx.AsyncClient | None = None
) -> str | None:
    """The artists an art track's description credits, or None."""
    html = await fetch_watch_page(video_id, client)
    if html is None:
        return None
    return parse_art_track_artists(parse_watch_description(html))
